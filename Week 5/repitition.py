def countUp():

    counter = 1
    while counter<=5:
        print(counter)
        counter = counter + 1
    
def main():
    countUp()

if __name__=="__main__":
    main()


def CountDown():
    count = 5
    while count >=0:
        print(count)
        count = count - 1

def main():
    CountDown()

if __name__=="__main__":
    main()
